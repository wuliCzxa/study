// ====================== 基础驱动函数 ======================
void delay_ms(unsigned int t) {
    unsigned int i, j;
    for(i=0; i<t; i++)
        for(j=0; j<120; j++);
}

// 74HC595 串行输出
void hc595_send(unsigned char dat) {
    unsigned char i;
    for(i=0; i<8; i++) {
        SER = (dat & 0x80);
        dat <<= 1;
        SRCLK = 0; SRCLK = 1;
    }
}

// 74HC595 输出锁存
void hc595_latch(void) {
    RCLK = 0; RCLK = 1;
}

// 软件清屏函数：逐行输出0x00
void ClearScreen(void) {
    unsigned char i;
    for(i = 0; i < 16; i++) {
        // 先选择第 i 行（通过 74HC138 控制）
        SelectRow(i);
        // 再发送两字节 0x00（16列清零）
        SendData(0x00);
        SendData(0x00);
        // 锁存数据（通过 74HC595 的 RCLK）
        LatchData();
    }
}

// ====================== 按键扫描函数 ======================
unsigned char scan_key() {
    if(key_l == 0) { delay_ms(20); if(key_l==0) return 'L'; }
    if(key_r == 0) { delay_ms(20); if(key_r==0) return 'R'; }
    if(key_u == 0) { delay_ms(20); if(key_u==0) return 'U'; }
    if(key_d == 0) { delay_ms(20); if(key_d==0) return 'D'; }
    if(key_m == 0) { delay_ms(20); if(key_m==0) return 'M'; }
    if(key_change == 0) { delay_ms(20); if(key_change==0) return 'C'; }
    return 0;
}

// ====================== 按键处理函数 ======================
void key_handler(unsigned char key) {
    switch(key) {
        case 'L':
            current_mode = SCROLL_LEFT;
            current_font_index = 0;   // 初始化显示第一组字模
            break;
        case 'R':
            current_mode = SCROLL_RIGHT;
            break;
        case 'U':
            current_mode = SCROLL_UP;
            break;
        case 'D':
            current_mode = SCROLL_DOWN;
            break;
        case 'M':
            current_mode = SCROLL_FULL;
            break;
        case 'C':   // 切换字模
            current_font_index++;
            if(current_font_index >= total_fonts) {
                current_font_index = 0;
            }
            break;
    }
}

// ====================== 显示函数 ======================
// 全屏覆盖显示
void display_full(unsigned char font[16][2]) {
    unsigned char row;
    for(row=0; row<16; row++) {
        hc595_send(font[row][0]);
        hc595_send(font[row][1]);
        hc595_latch();
        delay_ms(1);
    }
}

// 左滚动
void display_scroll_left(unsigned char font[16][2]) {
    unsigned char row, shift;
    unsigned int col;
    for(shift=0; shift<16; shift++) {   // 每次左移1列，共16列
        for(row=0; row<16; row++) {
            unsigned int line = (font[row][0] << 8) | font[row][1];
            line <<= shift;
            hc595_send(line >> 8);
            hc595_send(line & 0xFF);
            hc595_latch();
        }
        delay_ms(50);
    }
}

// 右滚动
void display_scroll_right(unsigned char font[16][2]) {
    unsigned char row, shift;
    for(shift=0; shift<16; shift++) {
        for(row=0; row<16; row++) {
            unsigned int line = (font[row][0] << 8) | font[row][1];
            line >>= shift;
            hc595_send(line >> 8);
            hc595_send(line & 0xFF);
            hc595_latch();
        }
        delay_ms(50);
    }
}

// 上滚动
void display_scroll_up(unsigned char font[16][2]) {
    unsigned char row, shift;
    for(shift=0; shift<16; shift++) {
        for(row=0; row<16; row++) {
            unsigned char r = (row+shift) % 16;
            hc595_send(font[r][0]);
            hc595_send(font[r][1]);
            hc595_latch();
        }
        delay_ms(80);
    }
}

// 下滚动
void display_scroll_down(unsigned char font[16][2]) {
    unsigned char row, shift;
    for(shift=0; shift<16; shift++) {
        for(row=0; row<16; row++) {
            unsigned char r = (row+16-shift) % 16;
            hc595_send(font[r][0]);
            hc595_send(font[r][1]);
            hc595_latch();
        }
        delay_ms(80);
    }
}

// ====================== 主程序 ======================
void main() {
    unsigned char key;
    while(1) {
        key = scan_key();
        if(key != 0) key_handler(key);

        switch(current_mode) {
            case SCROLL_LEFT:
                display_scroll_left(fonts[current_font_index]);
                break;
            case SCROLL_RIGHT:
                display_scroll_right(fonts[current_font_index]);
                break;
            case SCROLL_UP:
                display_scroll_up(fonts[current_font_index]);
                break;
            case SCROLL_DOWN:
                display_scroll_down(fonts[current_font_index]);
                break;
            case SCROLL_FULL:
                display_full(fonts[current_font_index]);
                break;
        }
    }
}
